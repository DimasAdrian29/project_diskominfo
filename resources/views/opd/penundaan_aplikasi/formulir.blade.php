    document.addEventListener('DOMContentLoaded', function() {
      const dropzone = document.getElementById('dropzone-container');
      const fileInput = document.getElementById('file_permohonan');

      ['dragenter', 'dragover'].forEach(eventName => {
        dropzone.addEventListener(eventName, (e) => {
          e.preventDefault();
          e.stopPropagation();
          dropzone.classList.add('border-amber-500', 'bg-surface-container');
        }, false);
      });

      ['dragleave', 'drop'].forEach(eventName => {
        dropzone.addEventListener(eventName, (e) => {
          e.preventDefault();
          e.stopPropagation();
          dropzone.classList.remove('border-amber-500', 'bg-surface-container');
        }, false);
      });

      fileInput.addEventListener('change', (e) => {
        if (e.target.files && e.target.files[0]) {
          console.log('File selected: ', e.target.files[0].name);
        }
      });
