<script>
    let currentDecisionType = 'terima';

    function openModal(type, opd, app) {
        currentDecisionType = type;
        const modal = document.getElementById('assessmentModal');
        const title = document.getElementById('modalTitle');
        const subtitle = document.getElementById('modalSubtitle');
        const opdElem = document.getElementById('modalOpdName');
        const appElem = document.getElementById('modalAppName');
        const iconContainer = document.getElementById('modalIconContainer');
        const icon = document.getElementById('modalIcon');
        const submitBtn = document.getElementById('modalSubmitBtn');
        const submitBtnText = document.getElementById('submitBtnText');
        const notesLabel = document.getElementById('notesLabel');
        const textarea = document.getElementById('evaluationNotes');

        opdElem.textContent = opd;
        appElem.textContent = app;

        if (type === 'terima') {
            title.textContent = 'Persetujuan Proposal Teknis';
            subtitle.textContent = 'Verifikasi dan rekomendasikan ke tahapan penganggaran';
            iconContainer.className = 'w-9 h-9 rounded-lg flex items-center justify-center text-white bg-emerald-600';
            icon.textContent = 'check_circle';
            submitBtn.className = 'px-5 py-2 rounded-lg bg-emerald-600 hover:bg-emerald-700 text-white text-xs font-bold transition-all shadow-xs flex items-center gap-1.5';
            submitBtnText.textContent = 'Kirim Persetujuan';
            notesLabel.innerHTML = 'Catatan Rekomendasi Teknis <span class="text-caption text-outline font-normal">(Opsional)</span>';
            textarea.placeholder = 'Contoh: Disetujui dengan catatan penggunaan database PostgreSQL terpusat dan API Gateway Diskominfo...';
            textarea.required = false;
        } else {
            title.textContent = 'Penolakan / Pengembalian Proposal';
            subtitle.textContent = 'Kirim catatan perbaikan arsitektur kepada OPD pengusul';
            iconContainer.className = 'w-9 h-9 rounded-lg flex items-center justify-center text-white bg-rose-600';
            icon.textContent = 'cancel';
            submitBtn.className = 'px-5 py-2 rounded-lg bg-rose-600 hover:bg-rose-700 text-white text-xs font-bold transition-all shadow-xs flex items-center gap-1.5';
            submitBtnText.textContent = 'Kirim Keputusan Penolakan';
            notesLabel.innerHTML = 'Alasan Penolakan & Evaluasi SPBE <span class="text-error font-bold">*Wajib Diisi</span>';
            textarea.placeholder = 'Tuliskan alasan penolakan: contoh belum memenuhi standar single login Riau atau terdapat duplikasi modul aplikasi...';
            textarea.required = true;
        }

        modal.classList.remove('hidden');
    }

    function closeModal() {
        const modal = document.getElementById('assessmentModal');
        modal.classList.add('hidden');
        document.getElementById('evaluationNotes').value = '';
    }

    function handleFormSubmit(event) {
        event.preventDefault();
        const app = document.getElementById('modalAppName').textContent;
        closeModal();

        showToast(
            currentDecisionType === 'terima' ? 'Proposal Disetujui' : 'Proposal Ditolak / Dikembalikan',
            `Keputusan untuk ${app} berhasil disimpan dan dikirim ke OPD terkait.`
        );
    }

    function showToast(title, msg) {
        const toast = document.getElementById('toastNotification');
        const toastTitle = document.getElementById('toastTitle');
        const toastMsg = document.getElementById('toastMessage');
        const toastIcon = document.getElementById('toastIcon');
        const toastIconBg = document.getElementById('toastIconBg');

        toastTitle.textContent = title;
        toastMsg.textContent = msg;

        if (currentDecisionType === 'terima') {
            toastIconBg.className = 'w-8 h-8 rounded-lg bg-emerald-100 text-emerald-700 flex items-center justify-center shrink-0';
            toastIcon.textContent = 'check';
        } else {
            toastIconBg.className = 'w-8 h-8 rounded-lg bg-rose-100 text-rose-700 flex items-center justify-center shrink-0';
            toastIcon.textContent = 'close';
        }

        toast.classList.remove('translate-y-24', 'opacity-0', 'pointer-events-none');
        setTimeout(() => {
            toast.classList.add('translate-y-24', 'opacity-0', 'pointer-events-none');
        }, 4000);
    }

    // Interactive Tab Filtering
    document.addEventListener('DOMContentLoaded', function() {
        const filterBtns = document.querySelectorAll('.filter-btn');
        const rows = document.querySelectorAll('.proposal-row');

        filterBtns.forEach(btn => {
            btn.addEventListener('click', function() {
                filterBtns.forEach(b => {
                    b.classList.remove('active', 'bg-primary', 'text-on-primary');
                    b.classList.add('text-on-surface-variant');
                });
                this.classList.add('active', 'bg-primary', 'text-on-primary');
                this.classList.remove('text-on-surface-variant');

                const filter = this.getAttribute('data-filter');
                rows.forEach(row => {
                    const rowStatus = row.getAttribute('data-status');
                    if (filter === 'all' || rowStatus === filter) {
                        row.style.display = '';
                    } else {
                        row.style.display = 'none';
                    }
                });
            });
        });

        // Category filter
        const catSelect = document.getElementById('kategoriSelect');
        if (catSelect) {
            catSelect.addEventListener('change', function() {
                const catVal = this.value;
                rows.forEach(row => {
                    const rowCat = row.getAttribute('data-category');
                    if (!catVal || rowCat === catVal) {
                        row.style.display = '';
                    } else {
                        row.style.display = 'none';
                    }
                });
            });
        }
    });
</script>

